export function getContinueWatching(): (MediaItem & { progress: WatchProgress })[] {
  return MOCK_WATCH_PROGRESS
    .map((progress) => {
      const media = getMediaById(progress.mediaId);
      if (!media) return null;
      return { ...media, progress };
    })
    .filter((item): item is MediaItem & { progress: WatchProgress } => item !== null)
    .sort((a, b) => new Date(b.progress.lastWatched).getTime() - new Date(a.progress.lastWatched).getTime());
}
